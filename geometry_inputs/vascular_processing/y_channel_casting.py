"""Generate the labelled Y casting system and native P1S ABS print projects.

The current mode reconstructs an equal-diameter channel on source branch axes.
The historical mode preserves original walls and transports their cap rings.

Millimetres in every generated asset. Casting and print transforms are separate.
Print support is generated by the real Bambu engine, never a invented G-code.
"""
