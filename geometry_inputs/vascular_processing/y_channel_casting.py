ROOT = Path(__file__).resolve().parents[1]
PORTS = [('INLET', 2), ('OUTLET_A', 3), ('OUTLET_B', 4)]


def bottomless(cfg):
    return cfg.get('fixture_mode') == 'bottomless_external_dovetail'


def retainer_arm_bottom(cfg, rim):
    """Independent arm-to-rim clearance; never raises the vessel body or fill."""
    return rim+(cfg.get('retainer_above_rim_mm', 0.) if bottomless(cfg) else 0.)


def part_names(cfg):
    if bottomless(cfg):
        from .bottomless_channel_fixture import part_names as fixture_parts
        return fixture_parts('Y')
    return ['Y_lumen_core', 'Y_casting_box_base_2mm', *['Y_retainer_'+n for n, _ in PORTS]]


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    def encode(v):
        if isinstance(v, np.ndarray): return v.tolist()
        if isinstance(v, np.generic): return v.item()
        if isinstance(v, Path): return str(v)
        raise TypeError(type(v).__name__)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False, default=encode)+'\n')


def load_config(path):
    cfg = yaml.safe_load(Path(path).read_text())
    validate_pdms_width_requirement(cfg)
    for key in ['source', 'planes', 'output']:
        cfg[key] = (ROOT/Path(cfg[key])).resolve()
    for key in ['pdms_floor_mm', 'wall_mm', 'base_mm', 'side_clearance_mm',
                'ring_step_mm', 'retainer_thickness_mm', 'collar_radial_width_mm']:
        if key == 'base_mm' and bottomless(cfg) and cfg[key] == 0: continue
        if not np.isfinite(cfg[key]) or cfg[key] <= 0:
            raise ValueError('POSITIVE_DIMENSION_REQUIRED: '+key)
    if not bottomless(cfg) and cfg['freeboard_mm'] < 2.2:
        raise ValueError('RETAINER_FEET_MUST_REMAIN_ABOVE_FILL_LEVEL')
    if cfg['bend_radius_to_lumen_radius'] < 2.0:
        raise ValueError('BEND_RADIUS_TOO_SMALL')
    if cfg['printer']['machine'] != 'Bambu Lab P1S 0.4 nozzle':
        raise ValueError('P1S_04_REQUIRED')
    if cfg.get('geometry_mode', 'original_wall') not in ['original_wall', 'uniform_diameter']:
        raise ValueError('UNKNOWN_GEOMETRY_MODE')
    if cfg.get('geometry_mode') == 'uniform_diameter':
        for key in ['diameter_mm', 'minimum_pdms_height_mm', 'junction_fillet_mm',
                    'parent_junction_fillet_mm', 'cad_tolerance_mm']:
            if not np.isfinite(cfg[key]) or cfg[key] <= 0:
                raise ValueError('POSITIVE_DIMENSION_REQUIRED: '+key)
        if cfg['minimum_pdms_height_mm'] < 9.:
            raise ValueError('PDMS_HEIGHT_AT_LEAST_9_MM_REQUIRED')
    if bottomless(cfg):
        from .bottomless_channel_fixture import validate_config
        validate_config(cfg)
    return cfg


def validate_pdms_width_requirement(cfg):
    if 'minimum_pdms_width_mm' in cfg:
        width = cfg['minimum_pdms_width_mm']
        if not np.isfinite(width) or width < 9.:
            raise ValueError('PDMS_WIDTH_AT_LEAST_9_MM_REQUIRED')
    if cfg.get('abs_dimensional_allowance') is not None:
        for dimension in ('width', 'height'):
            if cfg.get('minimum_pdms_'+dimension+'_mm', 0) < 9:
                raise ValueError('PDMS_'+dimension.upper()+'_AT_LEAST_9_MM_REQUIRED')
            minimum_cad(cfg, dimension)


def enforce_pdms_width(inner, cfg):
    """Widen the transverse Y cavity symmetrically, without moving the core.

    Already wider cavities are retained. Missing width in archived configs
    preserves historical dimensions. Current minima describe FINISHED PDMS;
    the ABS allowance policy determines the larger minimum CAD width.
    """
    validate_pdms_width_requirement(cfg)
    bounds = np.array(inner, dtype=float, copy=True)
    extra = max(0., minimum_cad(cfg, 'width')-np.ptp(bounds[:, 1]))
    bounds[:, 1] += [-extra/2, extra/2]
    return bounds


def pdms_width_qc(mold, inner, cfg, fill_z):
    """Measure the two INNER Y walls from mesh ray hits, not the outer box."""
    origin = np.r_[np.asarray(inner).mean(0), (cfg['base_mm']+fill_z)/2]
    distances = []
    for sign in [-1., 1.]:
        direction = np.array([0., sign, 0.])
        hits = mold.ray.intersects_location([origin], [direction])[0]
        along = (hits-origin)@direction
        positive = along[along > 1e-6]
        if not len(positive): raise ValueError('PDMS_SIDE_WALL_MISSING')
        distances.append(float(positive.min()))
    measured = sum(distances)
    nominal = float(np.ptp(np.asarray(inner)[:, 1]))
    requested = cfg.get('minimum_pdms_width_mm', 0.)
    budget = dimension_budget(cfg, 'width', measured)
    return dict(axis='Y', nominal_inner_width_mm=nominal, measured_inner_width_mm=measured,
        minimum_required_mm=requested, excludes_abs_walls=True, allowance=budget,
        passed=budget['passed'] and abs(measured-nominal) < 1e-5)


def pdms_height_qc(mold, inner, cfg, fill_z):
    """Measure the actual inner floor and rim, excluding base and freeboard."""
    origin = np.r_[np.asarray(inner).mean(0), cfg['base_mm']/2]
    hits = mold.ray.intersects_location([origin], [[0, 0, 1]])[0]
    above = hits[:, 2][hits[:, 2] > origin[2]+1e-6]
    if not len(above): raise ValueError('PDMS_FLOOR_MISSING')
    floor = float(above.min())
    measured_fill = float(mold.bounds[1, 2]-cfg['freeboard_mm'])
    measured = measured_fill-floor
    budget = dimension_budget(cfg, 'height', measured)
    return dict(axis='Z', measured_inner_floor_z_mm=floor, measured_fill_z_mm=measured_fill,
        measured_inner_height_mm=measured, excludes_abs_base_and_freeboard=True,
        allowance=budget, passed=budget['passed'] and abs(measured_fill-fill_z) < 1e-5
            and abs(floor-cfg['base_mm']) < 1e-5)


def box(bounds):
    bounds = np.asarray(bounds, float)
    m = trimesh.creation.box(bounds[1]-bounds[0])
    m.apply_translation(bounds.mean(0))
    return m


def union(meshes):
    return trimesh.boolean.union(meshes, engine='manifold')


def cylinder(xy, radius, z0, z1):
    m = trimesh.creation.cylinder(radius, z1-z0, sections=96)
    m.apply_translation([*xy, (z0+z1)/2])
    return m


def boundary_cycle(faces):
    """One ordered boundary of a labelled cap; never sort by floating angles."""
    edges = np.vstack([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]])
    unique, counts = np.unique(np.sort(edges, axis=1), axis=0, return_counts=True)
    boundary = unique[counts == 1]
    adjacent = {}
    for a, b in boundary:
        adjacent.setdefault(int(a), []).append(int(b))
        adjacent.setdefault(int(b), []).append(int(a))
    if not adjacent or any(len(v) != 2 for v in adjacent.values()):
        raise ValueError('CAP_BOUNDARY_NOT_SIMPLE_CYCLE')
    first = min(adjacent)
    ordered = [first]
    previous, current = first, adjacent[first][0]
    while current != first:
        if current in ordered: raise ValueError('MULTIPLE_CAP_BOUNDARIES')
        ordered.append(current)
        nxt = next(v for v in adjacent[current] if v != previous)
        previous, current = current, nxt
    if len(ordered) != len(adjacent): raise ValueError('MULTIPLE_CAP_BOUNDARIES')
    return np.array(ordered, dtype=int)


def import_source(cfg):
    if digest(cfg['source']) != cfg['source_sha256']:
        raise ValueError('SOURCE_SHA256_MISMATCH')
    poly = pv.read(cfg['source']).triangulate()
    if float(poly.field_data['coordinate_scale_to_m'][0]) != 1.0:
        raise ValueError('EXPLICIT_METRE_UNIT_CONTRACT_REQUIRED')
    labels = np.asarray(poly.cell_data['ModelFaceID'])
    if set(labels) != {1, 2, 3, 4}: raise ValueError('FOUR_LABELS_REQUIRED')
    # Promote float32 BEFORE unit conversion, preserving source precision.
    vertices = np.asarray(poly.points, dtype=float)*1000.0
    faces = poly.faces.reshape(-1, 4)[:, 1:]
    mesh = trimesh.Trimesh(vertices, faces, process=False)
    if not mesh.is_volume or len(mesh.split()) != 1:
        raise ValueError('SOURCE_NOT_ONE_CLOSED_POSITIVE_VOLUME')
    planes = json.loads(cfg['planes'].read_text())
    return mesh, labels, planes


def attach_ports(source, labels, planes, cfg):
    """Reuse every original wall face; replace ONLY cap faces with ring sweeps.

    Rigidly transporting each actual cap boundary avoids the circular-tube to
    irregular-cap seam. Circular arcs have exact tangent continuity with both
    adjacent straight sections. No radius interpolation or lumen rescaling.
    """
    shift_z = cfg['base_mm']+cfg['pdms_floor_mm']-source.bounds[0, 2]
    source = source.copy()
    source.apply_translation([0, 0, shift_z])
    radii = [planes[name]['radius_m']*1000 for name, _ in PORTS]
    bend = [r*cfg['bend_radius_to_lumen_radius'] for r in radii]
    # The arc outer surface cannot rise above its final centre, if R > radius.
    fill = max(shift_z+max(bend)+cfg['pdms_above_elbow_mm'],
               cfg['base_mm']+minimum_cad(cfg, 'height'))
    rim = fill+cfg['freeboard_mm']
    collar_z = rim+cfg['retainer_thickness_mm']
    top = collar_z+cfg['port_above_retainer_mm']
    vertices = source.vertices.tolist()
    faces = source.faces[labels == 1].tolist()
    port_records = []
    for (name, label), radius, R in zip(PORTS, radii, bend):
        origin = np.array(planes[name]['origin_m'], float)*1000+[0, 0, shift_z]
        n = np.asarray(planes[name]['normal'], float)
        n /= np.linalg.norm(n)
        if abs(n[2]) > 1e-8: raise ValueError('PLANAR_SOURCE_REQUIRED')
        ring_ids = boundary_cycle(source.faces[labels == label])
        ring = source.vertices[ring_ids]-origin
        axis = np.cross(n, [0., 0., 1.])
        straight = cfg['terminal_straight_mm']
        nodes = []
        for s in np.linspace(0, straight, int(np.ceil(straight/cfg['ring_step_mm']))+1)[1:]:
            nodes.append((origin+n*s, 0.))
        theta = np.linspace(0, np.pi/2, int(np.ceil(np.pi*R/2/cfg['ring_step_mm']))+1)
        for a in theta[1:]:
            nodes.append((origin+n*(straight+R*np.sin(a))+np.array([0, 0, R*(1-np.cos(a))]), a))
        bend_end = nodes[-1][0]
        for z in np.linspace(bend_end[2], top, int(np.ceil((top-bend_end[2])/cfg['ring_step_mm']))+1)[1:]:
            nodes.append((np.r_[bend_end[:2], z], np.pi/2))
        previous = ring_ids
        m = len(previous)
        for center, angle in nodes:
            rotation = Rotation.from_rotvec(axis*angle).as_matrix()
            coords = ring@rotation.T+center
            ids = np.arange(len(vertices), len(vertices)+m)
            vertices.extend(coords.tolist())
            for j in range(m):
                k = (j+1) % m
                faces.extend([[int(previous[j]), int(previous[k]), int(ids[k])],
                              [int(previous[j]), int(ids[k]), int(ids[j])]])
            previous = ids
        cap_center = len(vertices)
        vertices.append(np.asarray(vertices)[previous].mean(0).tolist())
        for j in range(m): faces.append([int(previous[j]), int(previous[(j+1) % m]), cap_center])
        port_records.append(dict(name=name, label_id=label, nominal_diameter_mm=2*radius,
            radius_mm=radius, bend_radius_mm=R, bend_start=origin+n*straight,
            original_origin_mm=origin, original_normal=n, vertical_axis=[0, 0, 1],
            top_center_mm=np.r_[bend_end[:2], top], collar_bottom_mm=collar_z,
            ring_vertex_count=m, centerline_mm=np.vstack([origin, *[c for c, a in nodes]]),
            analytical_centerline_tangent_jump_deg=0., cap_planarity_error_mm=float(np.max(np.abs(ring@n)))))
    core = trimesh.Trimesh(vertices, faces, process=False)
    core.remove_unreferenced_vertices()
    core.fix_normals()
    if not core.is_volume or len(core.split()) != 1: raise ValueError('PORT_SWEEP_NOT_ONE_SOLID')
    uncollared = core.copy()
    # Measure the rendered triangle normals on each actual old/new seam too.
    # A smooth analytic centreline alone cannot prove a well joined mesh.
    tree = cKDTree(core.vertices)
    for p in port_records:
        old_ring = boundary_cycle(source.faces[labels == p['label_id']])
        ids = tree.query(source.vertices[old_ring])[1]
        edges = {tuple(sorted((int(a), int(b)))) for a, b in zip(ids, np.roll(ids, -1))}
        adjacent = [i for i, e in enumerate(core.face_adjacency_edges) if tuple(sorted(map(int, e))) in edges]
        if len(adjacent) != len(ids): raise ValueError('UNWELDED_TERMINAL_SEAM')
        angles = np.rad2deg(core.face_adjacency_angles[adjacent])
        p['actual_seam_max_normal_angle_deg'] = float(angles.max())
        p['actual_seam_median_normal_angle_deg'] = float(np.median(angles))
    collars = [cylinder(p['top_center_mm'][:2], p['radius_mm']+cfg['collar_radial_width_mm'],
                        collar_z, collar_z+cfg['collar_thickness_mm']) for p in port_records]
    core = union([core, *collars])
    return core, uncollared, source, port_records, dict(
        source_z_translation_mm=shift_z, pdms_floor_z_mm=cfg['base_mm'],
        fill_z_mm=fill, rim_z_mm=rim, port_top_z_mm=top)


def retainer(port, inner, cfg, heights):
    """A removable open C fork straddles the wall, never the PDMS fill volume."""
    r = port['radius_mm']
    center = np.asarray(port['top_center_mm'][:2])
    outward = {'INLET': np.array([-1., 0.]), 'OUTLET_A': np.array([0., 1.]),
               'OUTLET_B': np.array([0., -1.])}[port['name']]
    axis = int(np.argmax(abs(outward)))
    wall = inner[0 if outward[axis] < 0 else 1, axis]
    d = abs(wall-center[axis])
    w = r+cfg['collar_radial_width_mm']+.8
    hole = r+cfg['retainer_fit_clearance_mm']
    t = cfg['retainer_thickness_mm']
    rim = heights['rim_z_mm']
    clearance = cfg['retainer_fit_clearance_mm']
    plate = box([[-w, -w, rim], [d+cfg['wall_mm']+1.45, w, rim+t]])
    cut = union([cylinder([0, 0], hole, rim-.1, rim+t+.1),
                 box([[-w-1, -hole, rim-.1], [0, hole, rim+t+.1]])])
    fork = trimesh.boolean.difference([plate, cut], engine='manifold')
    # Two 1.2-mm feet locate the wall with 0.25-mm clearance on each side.
    feet = [box([[d-clearance-1.2, -w, rim-2], [d-clearance, w, rim+.1]]),
            box([[d+cfg['wall_mm']+clearance, -w, rim-2],
                 [d+cfg['wall_mm']+clearance+1.2, w, rim+.1]])]
    m = union([fork, *feet])
    transform = np.eye(4)
    transform[:2, 0] = outward
    transform[:2, 1] = [-outward[1], outward[0]]
    transform[:2, 3] = center
    m.apply_transform(transform)
    return m


def mesh_info(m):
    return dict(watertight=bool(m.is_watertight), positive_volume=bool(m.is_volume),
                components=len(m.split()), faces=len(m.faces), bounds_mm=m.bounds,
                volume_mm3=float(m.volume), dimensions_mm=m.extents)


def geometry(cfg, out):
    if bottomless(cfg):
        from .bottomless_channel_fixture import geometry as fixture_geometry
        return fixture_geometry(cfg, out, 'Y')
    if cfg.get('geometry_mode') == 'uniform_diameter':
        from .y_uniform_channel import geometry as uniform_geometry
        return uniform_geometry(cfg, out)
    source, labels, planes = import_source(cfg)
    core, channel, original, ports, heights = attach_ports(source, labels, planes, cfg)
    inner = channel.bounds[:, :2]+np.array([[-cfg['side_clearance_mm']]*2, [cfg['side_clearance_mm']]*2])
    inner = enforce_pdms_width(inner, cfg)
    outer = inner+np.array([[-cfg['wall_mm']]*2, [cfg['wall_mm']]*2])
    blank = box([np.r_[outer[0], 0], np.r_[outer[1], heights['rim_z_mm']]])
    cavity = box([np.r_[inner[0], cfg['base_mm']], np.r_[inner[1], heights['rim_z_mm']+1]])
    mold = trimesh.boolean.difference([blank, cavity], engine='manifold')
    parts = {'Y_lumen_core': core, 'Y_casting_box_base_2mm': mold}
    for p in ports: parts['Y_retainer_'+p['name']] = retainer(p, inner, cfg, heights)
    assembly = out/'assembly'
    assembly.mkdir(parents=True, exist_ok=True)
    for name, mesh in parts.items(): mesh.export(assembly/(name+'.stl'))
    original.export(assembly/'Y_original_body_mm_reference.stl')
    channel.export(assembly/'Y_channel_without_positioning_collars_reference.stl')
    # Exact original wall retention is audited independently of the sweep.
    wall_ids = np.unique(source.faces[labels == 1])
    max_error = float(cKDTree(core.vertices).query(original.vertices[wall_ids])[0].max())
    mesh_qc = {name: mesh_info(m) for name, m in parts.items()}
    collision = {}
    keys = list(parts)
    for i, a in enumerate(keys):
        for b in keys[i+1:]:
            inter = trimesh.boolean.intersection([parts[a], parts[b]], engine='manifold')
            collision[a+' / '+b] = abs(float(inter.volume)) if len(inter.faces) and min(inter.extents) > 1e-8 else 0.
    summary = dict(units='mm', source_sha256=digest(cfg['source']), source_to_mm_scale=1000.,
        anatomical_scaling=False, original_body_translation_mm=[0, 0, heights['source_z_translation_mm']],
        heights=heights, pdms_minimum_floor_mm=float(core.bounds[0, 2]-cfg['base_mm']),
        wall_mm=cfg['wall_mm'], base_mm=cfg['base_mm'], cavity_xy_bounds_mm=inner,
        cavity_xy_size_mm=inner[1]-inner[0], mold_outer_size_mm=mold.extents,
        pdms_fill_height_mm=heights['fill_z_mm']-cfg['base_mm'],
        pdms_fill_volume_ml=float((np.prod(inner[1]-inner[0])*(heights['fill_z_mm']-cfg['base_mm'])
            - trimesh.boolean.intersection([core, box([np.r_[inner[0], cfg['base_mm']],
              np.r_[inner[1], heights['fill_z_mm']]])], engine='manifold').volume)/1000.),
        original_wall_max_vertex_error_mm=max_error, ports=ports, meshes=mesh_qc,
        assembly_pair_intersection_volume_mm3=collision,
        retainer_minimum_above_fill_mm=min(parts[k].bounds[0, 2] for k in keys if 'retainer' in k)-heights['fill_z_mm'],
        physical_fit_validated=False, optical_quality_validated=False)
    summary['pdms_width_qc'] = pdms_width_qc(mold, inner, cfg, heights['fill_z_mm'])
    summary['pdms_height_qc'] = pdms_height_qc(mold, inner, cfg, heights['fill_z_mm'])
    gates = dict(single_closed_parts=all(v['watertight'] and v['positive_volume'] and v['components'] == 1 for v in mesh_qc.values()),
        pdms_width_minimum=summary['pdms_width_qc']['passed'],
        pdms_height_minimum=summary['pdms_height_qc']['passed'],
        original_walls_preserved=max_error < 1e-5,
        requested_floor=abs(summary['pdms_minimum_floor_mm']-cfg['pdms_floor_mm']) < 1e-5,
        three_upward_ports=len(ports) == 3 and all(np.array_equal(p['vertical_axis'], [0, 0, 1]) for p in ports),
        welded_smooth_seams=all(p['actual_seam_max_normal_angle_deg'] < 3. for p in ports),
        no_assembly_penetration=max(collision.values()) < 1e-4,
        retainers_outside_pdms=summary['retainer_minimum_above_fill_mm'] > .3)
    summary['gates'] = gates
    summary['assembly_sha256'] = {p.name: digest(p) for p in sorted(assembly.glob('*.stl'))}
    summary['status'] = 'GEOMETRY_PASSED' if all(gates.values()) else 'GEOMETRY_FAILED'
    save(out/'geometry_qc.json', summary)
    save(out/'effective_config.json', cfg)
    if not all(gates.values()): raise ValueError('GEOMETRY_GATES_FAILED: '+str(gates))
    return parts, summary


def render(parts, summary, out):
    if summary.get('fixture_mode') == 'bottomless_external_dovetail':
        from .bottomless_channel_fixture import render as fixture_render
        return fixture_render(parts, summary, out)
    qc = out/'QC'
    qc.mkdir(exist_ok=True)
    colors = {'Y_lumen_core': '#c45142', 'Y_casting_box_base_2mm': '#84a9bb'}
    for name in ['assembly', 'top', 'side', 'core', 'exploded']:
        plot = pv.Plotter(off_screen=True, window_size=(1600, 1100))
        plot.set_background('white')
        for key, part in parts.items():
            if name == 'core' and key != 'Y_lumen_core': continue
            m = part.copy()
            if name == 'exploded':
                if 'retainer' in key: m.apply_translation([0, 0, 12])
                elif 'core' in key: m.apply_translation([0, 0, 6])
            plot.add_mesh(pv.wrap(m), color=colors.get(key, '#d4a64c'),
                          opacity=.22 if 'box' in key else 1., smooth_shading=True)
        if name in ['assembly', 'side', 'top']:
            lo, hi = np.asarray(summary['cavity_xy_bounds_mm'])
            fill = pv.Plane(center=[*(lo+hi)/2, summary['heights']['fill_z_mm']],
                            direction=(0, 0, 1), i_size=hi[0]-lo[0], j_size=hi[1]-lo[1])
            plot.add_mesh(fill, color='#64c6d1', opacity=.13)
        plot.add_text(f"Y channel | P1S / 0.4 mm / ABS\nPDMS height {summary['pdms_fill_height_mm']:.2f} mm | floor {summary['pdms_minimum_floor_mm']:.2f} mm | wall / base {summary['wall_mm']:.2f} mm",
                      font_size=14, color='#263238')
        plot.add_axes()
        plot.show_bounds(xtitle='X (mm)', ytitle='Y (mm)', ztitle='Z (mm)', fmt='%.2f',
                         font_size=12, color='#33434b', location='outer')
        if name == 'top': plot.view_xy()
        elif name == 'side': plot.view_xz()
        else: plot.view_isometric()
        plot.camera.zoom(.85)
        plot.screenshot(qc/(name+'.png'))
        plot.close()


def arrange(parts, out):
    if any('bottomless_box' in n for n in parts):
        from .bottomless_channel_fixture import arrange as fixture_arrange
        return fixture_arrange(parts, out)
    records, meshes = [], []
    centers = [(85., 90.), (150., 90.), (80., 140.), (105., 140.), (130., 140.)]
    for (name, part), xy in zip(parts.items(), centers):
        m = part.copy()
        rotation = np.eye(4)
        if 'retainer' in name:
            rotation[:3, :3] = Rotation.from_euler('x', 180, degrees=True).as_matrix()
            m.apply_transform(rotation)
        delta = np.r_[xy, 0.]-np.r_[m.bounds.mean(0)[:2], m.bounds[0, 2]]
        m.apply_translation(delta)
        transform = rotation.copy()
        transform[:3, 3] = delta
        records.append(dict(name=name, support_enabled='core' in name,
            casting_to_plate_transform=transform, plate_to_casting_transform=np.linalg.inv(transform),
            plate_bounds_mm=m.bounds))
        meshes.append(m)
    # A 7-mm envelope on every side reserves brim and native support space.
    envelopes = [m.bounds[:, :2]+[[-7, -7], [7, 7]] for m in meshes]
    for i, a in enumerate(envelopes):
        if not ((a[0] >= [20, 30]).all() and (a[1] <= 250).all()):
            raise ValueError('PLATE_BOUNDS_FAILED')
        for b in envelopes[i+1:]:
            if not ((a[1] < b[0]).any() or (b[1] < a[0]).any()):
                raise ValueError('PLATE_PART_ENVELOPES_OVERLAP')
    save(out/'print_layout.json', dict(passed=True, envelope_margin_mm=7, records=records))
    (out/'print_parts').mkdir(exist_ok=True)
    for m, r in zip(meshes, records): m.export(out/'print_parts'/(r['name']+'.stl'))
    return meshes, records


def get_profiles(cfg, out, material='ABS', discover=True):
    from .bambu_manufacturing import active_profiles
