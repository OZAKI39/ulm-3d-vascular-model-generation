"""Independent transcription of Zhang2011, DOI10.1088/1674-1056/20/11/114302.

Eqs(3),(4),(7),(8) are evaluated as residual equations, including Eq(9)'s
TOTAL pressure derivative. No project physics classes, APECSS or pair kernel.
SI input/output; state [R1,U1,x1,v1,R2,U2,x2,v2]. DOP853 with vector SI atol.
Phase is an audit control only: p=-Pa*sin(omega*t+phase). Defaults reproduce
the source's initial conditions, except chi=1 is an explicitly declared choice.
"""

from dataclasses import dataclass, asdict

import numpy as np
from scipy.integrate import solve_ivp


@dataclass(frozen=True)
class Parameters:
    R10: float = 3e-6
    R20: float = 6e-6
    D0: float = 120e-6
    f: float = 2.25e6
    Pa: float = 1e5
    P0: float = 1.01e5
    rho: float = 998.0
    mu: float = 0.001
    sigma: float = 0.051
    chi: float = 1.0
    mus: float = 1.27
    epsilon: float = 2e-9
    gamma: float = 1.07
    c: float = 1500.0
    phase: float = 0.0

    def __post_init__(self):
        if not all(np.isfinite(v) for v in asdict(self).values()):
            raise ValueError("Finite SI parameters required")
        if min(self.R10, self.R20, self.f, self.P0, self.rho, self.gamma, self.c) <= 0:
            raise ValueError("Positive radii/frequency/medium required")
        if min(self.Pa, self.mu, self.sigma, self.chi, self.mus, self.epsilon) < 0:
            raise ValueError("Negative pressure/shell parameter")
        if min(self.R10, self.R20) <= self.epsilon or self.D0 <= self.R10 + self.R20:
            raise ValueError("Overlapping spheres or invalid shell thickness")


def wall(R, U, A, R0, p):
    """Eq(9), its total derivative and separate gas/viscous/tension/shell terms."""
    gas = (p.P0 + 2 * p.sigma / R0) * (R0 / R) ** (3 * p.gamma)
    terms = np.array(
        [
            gas,
            -4 * p.mu * U / R,
            -2 * p.sigma / R,
            -4 * p.chi * (1 / R0 - 1 / R),
            -12 * p.mus * p.epsilon * U / (R * (R - p.epsilon)),
        ]
    )
    derivative = (
        -3 * p.gamma * gas * U / R
        - 4 * p.mu * (A / R - U**2 / R**2)
        + 2 * p.sigma * U / R**2
        - 4 * p.chi * U / R**2
        - 12
        * p.mus
        * p.epsilon
        * (A / (R * (R - p.epsilon)) - U**2 * (2 * R - p.epsilon) / (R * (R - p.epsilon)) ** 2)
    )
    return terms.sum(), derivative, terms


def residual(t, y, accelerations, p, details=False):
    R, U, x, v, S, W, z, w = y
    A, B, a, b = accelerations  # radial1, radial2, translation1, translation2
    D = z - x
    if min(R, S) <= p.epsilon or D <= 0:
        raise ValueError("Outside spherical domain")
    P1, Pd1, terms1 = wall(R, U, A, p.R10, p)
    P2, Pd2, terms2 = wall(S, W, B, p.R20, p)
    drive = -p.Pa * np.sin(2 * np.pi * p.f * t + p.phase)
    # Eqs(5),(6): velocity generated by the OTHER bubble at each center.
    incident1 = -(S**2) * W / D**2 + S**3 * w / D**3
    incident2 = R**2 * U / D**2 + R**3 * v / D**3
    F1, F2 = -12 * np.pi * p.mu * R * (v - incident1), -12 * np.pi * p.mu * S * (w - incident2)
    coupling1 = np.array(
        [
            -(S * S * B + 2 * S * W * W) / D,
            S * S * (v * W + S * b + 5 * W * w) / (2 * D**2),
            -(S**3) * w * (v + 2 * w) / (2 * D**3),
        ]
    )
    coupling2 = np.array(
        [
            -(R * R * A + 2 * R * U * U) / D,
            -R * R * (w * U + R * a + 5 * U * v) / (2 * D**2),
            -(R**3) * v * (w + 2 * v) / (2 * D**3),
        ]
    )
    radial1 = R * A + 1.5 * U * U - (P1 + R * Pd1 / p.c - p.P0 - drive) / p.rho - v * v / 4 - coupling1.sum()
    radial2 = S * B + 1.5 * W * W - (P2 + S * Pd2 / p.c - p.P0 - drive) / p.rho - w * w / 4 - coupling2.sum()
    # d/dt(R*S^2*W), not d/dt(R*S^2*W/D^2).
    trans1 = R * a / 3 + U * v + (U * S * S * W + 2 * R * S * W * W + R * S * S * B) / D**2
    trans1 -= S * S * (R * S * b + S * U * w + 5 * R * W * w) / D**3 + F1 / (2 * np.pi * p.rho * R * R)
    trans2 = S * b / 3 + W * w - (W * R * R * U + 2 * S * R * U * U + S * R * R * A) / D**2
    trans2 -= R * R * (R * S * a + R * W * v + 5 * S * U * v) / D**3 + F2 / (2 * np.pi * p.rho * S * S)
    res = np.array([radial1, radial2, trans1, trans2])
    if details:
        return dict(
            residual_m2_s2=res,
            drive_Pa=drive,
            wall_terms_Pa=np.array([terms1, terms2]),
            wall_pressure_Pa=np.array([P1, P2]),
            wall_pressure_derivative_Pa_s=np.array([Pd1, Pd2]),
            scattered_pressure_at_other_Pa=p.rho
            * np.array([(R * R * A + 2 * R * U * U) / D, (S * S * B + 2 * S * W * W) / D]),
            radial_coupling_m2_s2=np.array([coupling1, coupling2]),
            drag_N=np.array([F1, F2]),
        )
    return res


def acceleration(t, y, p):
    zero = residual(t, y, np.zeros(4), p)
    # Residual is affine in accelerations. Scaled basis keeps subtraction well conditioned.
    scales = (2 * np.pi * p.f) ** 2 * np.array([p.R10, p.R20, p.R10, p.R20])
    matrix = np.column_stack([residual(t, y, np.eye(4)[j] * scales[j], p) - zero for j in range(4)])
    return np.linalg.solve(matrix, -zero) * scales


def solve(p=Parameters(), cycles=64, samples=128, rtol=2e-10, steps=96, initial=None):
    initial = np.array([p.R10, 0, 0, 0, p.R20, 0, p.D0, 0]) if initial is None else np.asarray(initial)

    def rhs(t, y):
        A, B, a, b = acceleration(t, y, p)
        return [y[1], A, y[3], a, y[5], B, y[7], b]

    def contact(t, y):
        return y[6] - y[2] - y[0] - y[4]

    contact.terminal, contact.direction = True, -1
    scale = min(p.R10, p.R20)
    atol = rtol * 0.01 * np.array([scale, scale * 2 * np.pi * p.f] * 4)
    t = np.linspace(0, cycles / p.f, round(cycles * samples) + 1)
    result = solve_ivp(
        rhs,
        (0, t[-1]),
        initial,
        t_eval=t,
        rtol=rtol,
        atol=atol,
        method="DOP853",
        max_step=1 / (steps * p.f),
        events=contact,
    )
    if not result.success:
        raise RuntimeError(result.message)
    return dict(
        time_s=result.t,
        state=result.y.T,
        nfev=result.nfev,
        contact_reached=bool(result.t_events[0].size),
        rtol=rtol,
        atol=atol.tolist(),
    )
