"""Build conservative KEEP/DELETE/REVIEW manifests; does not delete."""
from collections import defaultdict
import importlib.util
import json
from pathlib import Path
import re
from audit_inventory import AUDIT, PROJECT, ROOT, dump_csv, dump_json, test_temp

CURRENT = ('pfpd_candidate_v1', 'pfpd_at1_evolution_v1', 'pfpd_at1_coupling_stability_audit_v1',
           'pfpd_at1_branch_stability_tracking_v1', 'pfpd_at1_spatial_discretization_audit_v2',
           'pfpd_at1_spectral_split_v1', 'pfpd_at1_c5_activation_stationarity_audit_v1',
           'pfpd_at1_petsc_vi_solver_v1', 'pfpd_at1_c5_stability_v1',
           'pfpd_at1_c7_early_branch_v1', 'pfpd_at1_activation_mesh_dependence_audit_v1')


def main():
    rows = json.loads((AUDIT / 'INVENTORY_RAW.json').read_text())
    refs = json.loads((AUDIT / 'REFERENCE_SCAN_BEFORE.json').read_text())['resolved']
    direct = defaultdict(set); directories = defaultdict(set)
    for r in refs:
        if r['within_repository']:
            if r['is_directory']:
                # A cwd/module/namespace mentioned in prose is not a dependency
                # on every descendant cache. Explicit artifact links and JSON
                # cache/state directory pointers protect their complete payload.
                if r['kind'] in ('markdown_link', 'json_path') and len(Path(r['target']).parts) > 2:
                    directories[r['target']].add(r['source'])
            else:
                direct[r['target']].add(r['source'])
    by_source_name = defaultdict(list)
    for row in rows:
        if row['extension'] == '.py' and row['type'] == 'file':
            by_source_name[Path(row['path']).name].append(row['path'])
    baseline = json.loads((AUDIT / 'BASELINE_TESTS.json').read_text())
    assert baseline['counts'] == {'passed': 412, 'failed': 3, 'skipped': 0}
    assert baseline['collected_count'] == 415

    for row in rows:
        path = row['path']; p = Path(path); parts = p.parts; name = p.name
        cited = set(direct[path])
        for parent in p.parents:
            cited.update(directories.get(str(parent), set()))
        row.update(referenced_by_review=';'.join(sorted(cited)), regenerable_from='',
                   candidate_category='KEEP', cleanup_kind='', scientific_dependency='HISTORICAL_BASELINE', reason='Retain historical research evidence; no proof of redundant or disposable role.')
        generated = None
        if row['extension'] in ('.pyc', '.pyo'):
            try:
                source = Path(importlib.util.source_from_cache(str(ROOT / path))) if '__pycache__' in parts else (ROOT / path).with_suffix('.py')
            except ValueError:
                source = None
            if source and source.is_file():
                generated = ('PYTHON_BYTECODE', 'Interpreter-generated bytecode; corresponding Python source is retained.', str(source))
        elif row['extension'] in ('.nbc', '.nbi'):
            module = name.split('.')[0] + '.py'
            sources = by_source_name.get(module, [])
            if sources:
                canonical = sorted(sources, key=lambda s: ('/source_snapshot/' in s, not s.startswith('clot_clearance/pd_clot/'), len(s)))[0]
                generated = ('NUMBA_CACHE', 'Numba compiled cache/index; matching source module is present and remains retained.', canonical)
        elif any(k in parts for k in ('.pytest_cache', '.mypy_cache', '.ruff_cache', '.ipynb_checkpoints', 'htmlcov')) or name in ('.coverage', 'coverage.xml'):
            generated = ('TOOL_CACHE', 'Generated test/type/lint/coverage/editor checkpoint data; not scientific acceptance evidence.', 'Retained tests and tooling configuration')
        elif name.startswith('fontlist-v') and name.endswith('.json') and any('matplotlib' in part for part in parts):
            generated = ('MATPLOTLIB_CACHE', 'Generated font discovery cache; no figures or fonts are deleted.', 'Matplotlib font discovery from retained environment')
        elif '/external/julia_depot/compiled/v1.10/' in path and row['extension'] in ('.ji', '.so', '.pidfile'):
            generated = ('JULIA_COMPILER_CACHE', 'Julia package precompile cache; installed runtime, package sources, artifacts, Project and Manifest are retained.',
                         'verification/pfpd_candidate_v1/provenance/REPRODUCE.sh; external/julia_env and julia_depot/packages')
        elif path == 'clot_clearance/verification/pfpd_candidate_v1/external/julia-1.10.12.tar.gz':
            identity = json.loads((PROJECT/'verification/pfpd_candidate_v1/resources/JULIA_DOWNLOAD.json').read_text())
            assert row['hash'] == identity['sha256']
            assert (PROJECT/'verification/pfpd_candidate_v1/external/julia-1.10.12/bin/julia').is_file()
            generated = ('INSTALLER_ARCHIVE', 'Verified official installer already extracted into retained Julia runtime; archive is not a runtime dependency.',
                         identity['url'] + '; pinned SHA256 in resources/JULIA_DOWNLOAD.json')
        elif test_temp(path):
            # These directories were passed as pytest basetemp; children are generated fixtures.
            generated = ('PYTEST_TEMPORARY', 'Historical pytest basetemp output; retained tests regenerate fixtures and retained BASELINE/FINAL logs carry acceptance evidence.',
                         'clot_clearance/tests; pytest tests -q using a fresh --basetemp')
        elif name in ('.DS_Store', 'Thumbs.db') or name.endswith(('~', '.swp', '.swo')):
            generated = ('EDITOR_OS_TRASH', 'OS/editor generated artifact, not source or scientific evidence.', 'Not required')
        elif row['extension'] == '.log' and row['size_bytes'] == 0 and 'provenance' not in parts and not re.search(r'BASELINE|FINAL|pytest|failure|solver|hardware', name, re.I):
            generated = ('EMPTY_CONSOLE_LOG', 'Empty non-provenance console capture; contains no diagnostics or scientific values.', 'Not required; producing script retained')

        if '.git' in parts or parts[0] != 'clot_clearance':
            row.update(reason='Git metadata/history or outer-repository files: outside deletion scope.', scientific_dependency='GIT_OR_OUTER_REPOSITORY')
        elif cited:
            row.update(reason='Directly referenced by a formal document/status/summary or inside its linked artifact directory.', scientific_dependency='REFERENCED_ARTIFACT')
        elif row['extension'] == '.pdf' or 'references' in parts:
            row.update(reason='Paper/reference material or retained PDF figure; protected regardless of duplication.', scientific_dependency='PAPER_REFERENCE')
        elif generated:
            kind, reason, origin = generated
            row.update(candidate_category='TRACKED_DELETE_CANDIDATE' if row['git_tracked'] else 'DELETE_SAFE',
                       cleanup_kind=kind, reason=reason, regenerable_from=origin, scientific_dependency='REGENERABLE_ARTIFACT')
        elif row['git_tracked']:
            row.update(reason='Tracked file retained; AGGRESSIVE_TRACKED_CLEANUP=false.', scientific_dependency='TRACKED_BASELINE')
        elif row['type'] == 'symlink':
            row.update(reason='Retain runtime/source symlink without following it.', scientific_dependency='RUNTIME_ENVIRONMENT')
        elif len(parts) > 1 and parts[1] in ('pd_clot', 'tests', 'configs', 'scripts'):
            row.update(reason='Production/candidate source, tests, configuration or historical reproduction entry point.',
                       scientific_dependency={'pd_clot': 'CURRENT_SOURCE', 'tests': 'CURRENT_TEST', 'configs': 'CURRENT_CONFIG', 'scripts': 'SOURCE_OR_REPRODUCTION'}[parts[1]])
        elif any(k in parts for k in ('python_deps', 'julia_depot', 'julia-1.10.12', 'julia_env', 'pdf_tools')):
            row.update(reason='Installed runtime, package sources/artifacts or tools required by saved reproduction instructions.', scientific_dependency='RUNTIME_ENVIRONMENT')
        elif row['extension'] == '.md' or 'provenance' in parts or name.startswith(('PRE_', 'POST_')) or row['extension'] in ('.toml', '.lock'):
            row.update(reason='Formal documentation, configuration, dependency lock or scientific provenance retained.', scientific_dependency='CURRENT_VERIFICATION')
        elif any(k in parts for k in CURRENT) and any(k in parts for k in ('results', 'verification')):
            row.update(reason='Current validated milestone, accepted/failed scientific state, table, figure or audit evidence.', scientific_dependency='NEXT_ROUND_DEPENDENCY' if ('c5' in path or 'c7' in path) else 'CURRENT_VERIFICATION')
        elif row['extension'] in ('.tmp', '.temp', '.bak', '.orig', '.pid') or any(k in parts for k in ('scratch', 'temporary', 'intermediate', 'download_cache', 'wheel_cache', 'failed_downloads')):
            row.update(candidate_category='REVIEW_REQUIRED', reason='Temporary-looking item lacks proof of complete regenerability and non-dependency; retained.')
        elif any(k.startswith('build_') for k in parts) or '/tests/full/' in path or '/test_artifacts/' in path:
            row.update(candidate_category='REVIEW_REQUIRED', reason='Build/test-adjacent material may contain reference downloads or historical failure evidence; do not delete by directory name.')
        elif row['extension'] == '.log':
            row.update(candidate_category='REVIEW_REQUIRED', reason='Historical nonempty log; precise scientific/provenance role not proven redundant. Retained.')
        if row['type'] not in ('file', 'symlink') and row['candidate_category'] == 'DELETE_SAFE':
            row.update(candidate_category='REVIEW_REQUIRED', reason='Nonregular filesystem object; requires manual review.')
        assert not (row['candidate_category'] == 'DELETE_SAFE' and row['referenced_by_review'])

    # Pytest runners copy source into their temporary output. Never discard a
    # unique historical source version under the generic temporary-file rule.
    source_ext = {'.py', '.jl', '.cpp', '.h', '.f90', '.sh'}
    retained_source_hashes = defaultdict(list)
    for row in rows:
        if row['extension'] in source_ext and row['candidate_category'] != 'DELETE_SAFE':
            retained_source_hashes[row['hash']].append(row['path'])
    for row in rows:
        if row['extension'] in source_ext and row['candidate_category'] == 'DELETE_SAFE':
            canonical = retained_source_hashes.get(row['hash'], [])
            if canonical and row['cleanup_kind'] == 'PYTEST_TEMPORARY':
                canonical.sort(key=lambda p: ('/pd_clot/' not in p or '/source_snapshot/' in p, len(p)))
                row.update(cleanup_kind='PYTEST_SOURCE_DUPLICATE', regenerable_from=canonical[0],
                           reason='Source snapshot copied by pytest; byte-identical retained canonical source exists (SHA256 checked); no production module is removed.')
            else:
                row.update(candidate_category='REVIEW_REQUIRED', cleanup_kind='',
                           reason='Temporary source snapshot lacks a byte-identical retained canonical; preserve potentially unique historical source.')

    # Hash equality alone never makes accepted data, references or tracked files disposable.
    groups = defaultdict(list)
    for row in rows:
        if row['type'] == 'file' and row['extension'] in ('.npz', '.npy', '.pkl', '.pickle', '.png', '.pdf', '.log', '.py', '.jl', '.cpp', '.h', '.f90', '.sh'):
            groups[(row['extension'], row['hash'])].append(row)
    duplicates = []
    for (ext, sha), group in groups.items():
        if len(group) < 2:
            continue
        ranked = sorted(group, key=lambda r: (r['candidate_category'] == 'DELETE_SAFE', not bool(r['referenced_by_review']), not r['git_tracked'], '/results/' not in r['path'], len(r['path'])))
        retained = [r for r in ranked if r['candidate_category'] != 'DELETE_SAFE']
        canonical = retained[0]['path'] if retained else ''
        other = [r for r in ranked if r['path'] != canonical]
        duplicates.append(dict(hash=sha, extension=ext, canonical=canonical,
                               duplicates=json.dumps([r['path'] for r in other]),
                               potential_bytes_saved=sum(r['size_bytes'] for r in ranked[1:]),
                               approved_delete_bytes=sum(r['size_bytes'] for r in group if r['candidate_category'] == 'DELETE_SAFE'),
                               decision='Delete only independently proven disposable artifacts; preserve all scientific/reference/linked copies.',
                               canonical_status='RETAINED' if canonical else 'All copies are regenerable pytest products; no retained scientific canonical implied'))

    fields = ['path', 'type', 'size_bytes', 'mtime', 'mtime_ns', 'git_tracked', 'git_status', 'extension', 'top_level_group',
              'candidate_category', 'reason', 'cleanup_kind', 'scientific_dependency', 'regenerable_from', 'referenced_by_review', 'hash', 'link_target']
    dump_csv('FILE_INVENTORY.csv', rows, fields)
    dump_json('CLASSIFIED_INVENTORY.json', rows)
    keep = [r for r in rows if r['candidate_category'] != 'DELETE_SAFE']
    delete = [r for r in rows if r['candidate_category'] == 'DELETE_SAFE']
    review = [r for r in rows if r['candidate_category'] == 'REVIEW_REQUIRED']
    tracked = [r for r in rows if r['candidate_category'] == 'TRACKED_DELETE_CANDIDATE']
    dump_csv('KEEP_MANIFEST.csv', keep, ['path', 'reason', 'scientific_dependency', 'candidate_category', 'size_bytes', 'hash'])
    dump_csv('DELETE_MANIFEST.csv', [{**r, 'category': r['cleanup_kind']} for r in delete], ['path', 'size_bytes', 'category', 'reason', 'regenerable_from', 'referenced_by_review', 'git_tracked', 'hash', 'type', 'link_target'])
    dump_csv('REVIEW_REQUIRED.csv', review, ['path', 'size_bytes', 'reason', 'scientific_dependency', 'hash'])
    dump_csv('TRACKED_DELETE_CANDIDATES.csv', tracked, ['path', 'size_bytes', 'cleanup_kind', 'reason', 'hash'])
    dump_csv('DUPLICATE_FILES.csv', duplicates, ['hash', 'extension', 'canonical', 'duplicates', 'potential_bytes_saved', 'approved_delete_bytes', 'decision', 'canonical_status'])
    stats = {}
    for category in ('KEEP', 'DELETE_SAFE', 'TRACKED_DELETE_CANDIDATE', 'REVIEW_REQUIRED'):
        subset = [r for r in rows if r['candidate_category'] == category]
        stats[category] = {'count': len(subset), 'bytes': sum(r['size_bytes'] for r in subset)}
    stats.update(total_files_scanned=len(rows), total_bytes=sum(r['size_bytes'] for r in rows),
                 tracked_bytes=sum(r['size_bytes'] for r in rows if r['git_tracked']),
                 untracked_bytes=sum(r['size_bytes'] for r in rows if not r['git_tracked']),
                 estimated_bytes_saved=sum(r['size_bytes'] for r in delete),
                 AGGRESSIVE_TRACKED_CLEANUP=False,
                 largest_20_delete_items=[{'path': r['path'], 'size_bytes': r['size_bytes'], 'category': r['cleanup_kind']} for r in sorted(delete, key=lambda r:r['size_bytes'], reverse=True)[:20]])
    dump_json('PRE_DELETE_SUMMARY.json', stats)
    (AUDIT / 'PRE_DELETE_SUMMARY.log').write_text(json.dumps(stats, indent=2, ensure_ascii=False) + '\n')
    print(json.dumps({k:v for k,v in stats.items() if k != 'largest_20_delete_items'}, ensure_ascii=False), flush=True)


if __name__ == '__main__':
    main()
